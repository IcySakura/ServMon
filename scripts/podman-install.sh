#!/usr/bin/env bash
# Installs servmon as a rootless Podman pod managed by systemd (Quadlet).
#
#   scripts/podman-install.sh            install or update, then (re)start
#   scripts/podman-install.sh uninstall  stop and remove the units (data/ is kept)
#
# Writes ~/.config/containers/systemd/servmon*.{pod,container}; systemd turns them into
#   servmon-pod.service  servmon-collector.service  servmon-prometheus.service
#   servmon-grafana.service  [servmon-tunnel.service]
# Settings come from .env (see .env.example). Re-run after changing .env.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
QDIR="${XDG_CONFIG_HOME:-$HOME/.config}/containers/systemd"
UDIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNITS=(servmon-collector servmon-prometheus servmon-grafana servmon-tunnel)

stop_all() {
  systemctl --user stop servmon-pod.service "${UNITS[@]/%/.service}" 2>/dev/null || true
}

# The older native setup (scripts/install-services.sh) used the same unit names.
remove_native_units() {
  local found=0
  for f in "$UDIR"/servmon-{collector,prometheus,grafana}.service "$UDIR/servmon.target"; do
    [[ -f $f ]] && grep -q "scripts/run-\|servmon-collector.service" "$f" && found=1
  done
  ((found)) || return 0
  echo "removing the native systemd units from scripts/install-services.sh"
  systemctl --user disable --now servmon.target servmon-{collector,prometheus,grafana}.service 2>/dev/null || true
  rm -f "$UDIR"/servmon-{collector,prometheus,grafana}.service "$UDIR/servmon.target"
}

if [[ ${1:-} == uninstall ]]; then
  stop_all
  rm -f "$QDIR"/servmon.pod "$QDIR"/servmon-*.container
  systemctl --user daemon-reload
  podman secret rm servmon-tunnel-token >/dev/null 2>&1 || true
  echo "servmon units removed; data is still in ${SERVMON_DATA:-$ROOT/data}"
  exit 0
fi

[[ -f $ROOT/.env ]] || "$ROOT/scripts/setup.sh"
set -a; . "$ROOT/.env"; set +a
abspath() { case $1 in /*) echo "$1" ;; ~*) echo "$HOME${1#\~}" ;; *) echo "$ROOT/${1#./}" ;; esac; }
DATA=$(abspath "${SERVMON_DATA:-./data}")
SSHD=$(abspath "${SSH_DIR:-$HOME/.ssh}")
U=${SERVMON_UID:-$(id -u)} G=${SERVMON_GID:-$(id -g)}
ADDR=${BIND_ADDR:-127.0.0.1}
mkdir -p "$DATA"/{prometheus,grafana,archive} "$QDIR"
touch "$ROOT/deploy/grafana/grafana.env"

echo "building localhost/servmon-collector"
podman build -q -t localhost/servmon-collector --build-arg UID="$U" --build-arg GID="$G" \
  -f "$ROOT/deploy/docker/collector.Dockerfile" "$ROOT" >/dev/null

remove_native_units
stop_all

cat > "$QDIR/servmon.pod" <<EOF
# generated by scripts/podman-install.sh; edit .env and re-run instead
[Unit]
Description=servmon pod (collector + Prometheus + Grafana)

[Pod]
PodName=servmon
# containers run as you, so files under data/ stay owned by you
UserNS=keep-id
PublishPort=$ADDR:${GRAFANA_PORT:-3300}:3300
PublishPort=127.0.0.1:${PROMETHEUS_PORT:-9390}:9090
PublishPort=127.0.0.1:${COLLECTOR_PORT:-9877}:9877

[Install]
WantedBy=default.target
EOF

cat > "$QDIR/servmon-collector.container" <<EOF
# generated by scripts/podman-install.sh
[Unit]
Description=servmon collector (SSH sessions to the servers)

[Container]
ContainerName=servmon-collector
Image=localhost/servmon-collector
Pod=servmon.pod
Volume=$ROOT/servmon:/servmon/servmon:ro
Volume=$ROOT/config.toml:/servmon/config.toml:ro
Volume=$SSHD:/home/servmon/.ssh:ro
Volume=$DATA/archive:/servmon/data/archive

[Service]
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
EOF

cat > "$QDIR/servmon-prometheus.container" <<EOF
# generated by scripts/podman-install.sh
[Unit]
Description=servmon Prometheus

[Container]
ContainerName=servmon-prometheus
Image=docker.io/prom/prometheus:v3.16.0
Pod=servmon.pod
User=$U:$G
Volume=$ROOT/deploy/prometheus.yml:/etc/prometheus/prometheus.yml:ro
Volume=$DATA/prometheus:/prometheus
Exec=--config.file=/etc/prometheus/prometheus.yml --storage.tsdb.path=/prometheus \\
     --storage.tsdb.retention.time=${RETENTION_TIME:-2y} --storage.tsdb.retention.size=${RETENTION_SIZE:-40GB} \\
     --web.enable-admin-api --query.timeout=2m

[Service]
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
EOF

cat > "$QDIR/servmon-grafana.container" <<EOF
# generated by scripts/podman-install.sh
[Unit]
Description=servmon Grafana

[Container]
ContainerName=servmon-grafana
Image=docker.io/grafana/grafana:13.3.1
Pod=servmon.pod
User=$U:$G
Volume=$ROOT/deploy/grafana:/servmon/deploy/grafana:ro
Volume=$DATA/grafana:/servmon/data/grafana
Environment=SERVMON_ROOT=/servmon PROM_URL=http://127.0.0.1:9090 GF_SERVER_HTTP_ADDR=0.0.0.0
Environment=GF_PATHS_CONFIG=/servmon/deploy/grafana/grafana.ini GF_PATHS_DATA=/servmon/data/grafana
Environment=GF_PATHS_LOGS=/servmon/data/grafana/log GF_PATHS_PLUGINS=/servmon/data/grafana/plugins
Environment=GF_PATHS_PROVISIONING=/servmon/deploy/grafana/provisioning
Environment=GF_SECURITY_ADMIN_PASSWORD=${GRAFANA_ADMIN_PASSWORD:-admin}
# your own Grafana settings (auth, public URL, ...): see deploy/grafana/grafana.env.example
EnvironmentFile=$ROOT/deploy/grafana/grafana.env

[Service]
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
EOF

# Optional: a Cloudflare Tunnel connector inside the pod (origin: http://localhost:3300).
rm -f "$QDIR/servmon-tunnel.container"
if [[ -n ${TUNNEL_TOKEN:-} ]]; then
  printf %s "$TUNNEL_TOKEN" | podman secret create --replace servmon-tunnel-token - >/dev/null
  cat > "$QDIR/servmon-tunnel.container" <<EOF
# generated by scripts/podman-install.sh (TUNNEL_TOKEN is set in .env)
[Unit]
Description=servmon tunnel connector (cloudflared)
After=servmon-grafana.service

[Container]
ContainerName=servmon-tunnel
Image=docker.io/cloudflare/cloudflared:2026.11.0
Pod=servmon.pod
Exec=tunnel --no-autoupdate run
Secret=servmon-tunnel-token,type=env,target=TUNNEL_TOKEN

[Service]
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
EOF
else
  podman secret rm servmon-tunnel-token >/dev/null 2>&1 || true
fi

systemctl --user daemon-reload
systemctl --user start servmon-pod.service
for u in "${UNITS[@]}"; do
  [[ -f $QDIR/$u.container ]] && systemctl --user restart "$u.service"
done
echo
systemctl --user --no-pager --no-legend list-units 'servmon*'
echo
echo "Grafana: http://$ADDR:${GRAFANA_PORT:-3300}   Prometheus: http://127.0.0.1:${PROMETHEUS_PORT:-9390}"
[[ $(loginctl show-user "$USER" -p Linger --value 2>/dev/null) == yes ]] ||
  echo "To keep servmon running while you are logged out and after reboots:  loginctl enable-linger $USER"
